CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS users
(
    user_id    UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    email      VARCHAR(255) UNIQUE NOT NULL,
    first_name VARCHAR(50),
    last_name  VARCHAR(50),
    password   VARCHAR(255),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS user_authorities
(
    user_id   UUID        NOT NULL,
    authority VARCHAR(50) NOT NULL,
    CONSTRAINT fk_user_authorities_users FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS inquiries
(
    inquiry_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email      VARCHAR(255),
    title      VARCHAR(255),
    message    TEXT,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS refresh_tokens
(
    token_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    UUID NOT NULL UNIQUE,
    token      TEXT,
    created_at TIMESTAMPTZ,
    expires_at TIMESTAMPTZ,
    CONSTRAINT fk_refresh_tokens_users FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS user_assets
(
    asset_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    UUID        NOT NULL,
    type       VARCHAR(20) NOT NULL,
    url        TEXT        NOT NULL,
    path       TEXT        NOT NULL,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_user_assets_users FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS otp_auth
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    otp_code       VARCHAR(255),
    attempts       INTEGER NOT NULL DEFAULT 0,
    active         BOOLEAN NOT NULL DEFAULT FALSE,
    verified_token UUID UNIQUE,
    contact        VARCHAR(255) UNIQUE,
    updated_at     TIMESTAMPTZ,
    expires_at     TIMESTAMPTZ,
    cooldown       TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_user_authorities_user_id ON user_authorities (user_id);
CREATE INDEX IF NOT EXISTS idx_user_assets_user_id ON user_assets (user_id);
CREATE INDEX IF NOT EXISTS idx_refresh_tokens_user_id ON refresh_tokens (user_id);

CREATE TABLE IF NOT EXISTS chatbot_conversations
(
    conversation_id UUID PRIMARY KEY,
    session_id      UUID UNIQUE NOT NULL,
    company_key     VARCHAR(120) NOT NULL,
    company_name    VARCHAR(255) NOT NULL,
    language        VARCHAR(8) NOT NULL,
    status          VARCHAR(40) NOT NULL,
    message_count   INTEGER NOT NULL DEFAULT 0,
    preview         TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ended_at        TIMESTAMPTZ,
    expires_at      TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS chatbot_messages
(
    message_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id UUID NOT NULL,
    sequence_number INTEGER NOT NULL,
    role            VARCHAR(24) NOT NULL,
    content         TEXT NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_chatbot_messages_conversations
        FOREIGN KEY (conversation_id) REFERENCES chatbot_conversations (conversation_id) ON DELETE CASCADE,
    CONSTRAINT uk_chatbot_messages_conversation_sequence UNIQUE (conversation_id, sequence_number)
);

CREATE INDEX IF NOT EXISTS idx_chatbot_conversations_company_created
    ON chatbot_conversations (company_key, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_chatbot_conversations_expires
    ON chatbot_conversations (expires_at);

CREATE INDEX IF NOT EXISTS idx_chatbot_messages_conversation_sequence
    ON chatbot_messages (conversation_id, sequence_number);
