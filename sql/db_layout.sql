DROP TABLE IF EXISTS stores CASCADE;
DROP TABLE IF EXISTS orders CASCADE ;
DROP TABLE IF EXISTS customers CASCADE ;
DROP TABLE IF EXISTS products CASCADE ;
DROP TABLE IF EXISTS order_items CASCADE ;
DROP TABLE IF EXISTS user_authorities CASCADE ;
DROP TABLE IF EXISTS refresh_tokens CASCADE ;
DROP TABLE IF EXISTS inquiries CASCADE ;
DROP TABLE IF EXISTS user_assets CASCADE ;
DROP TABLE IF EXISTS otp_auth CASCADE ;
DROP TABLE IF EXISTS users CASCADE;

CREATE TABLE users(user_id    UUID PRIMARY KEY NOT NULL,
                   email      VARCHAR(255) UNIQUE NOT NULL,
                   first_name VARCHAR(50) NOT NULL,
                   last_name  VARCHAR(50) NOT NULL,
                   password   VARCHAR(255) NOT NULL,
                   created_at TIMESTAMPTZ DEFAULT Current_timestamp);

CREATE TABLE user_authorities(user_id   UUID NOT NULL,
                              authority VARCHAR(50) NOT NULL,
                              CONSTRAINT fk_user_authorities_users FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE );

CREATE TABLE inquiries(inquiry_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       email      VARCHAR(255) NOT NULL,
                       title      VARCHAR(255),
                       message    TEXT,
                       created_at TIMESTAMPTZ DEFAULT Current_timestamp);

CREATE TABLE refresh_tokens(token_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            user_id    UUID NOT NULL,
                            token      TEXT NOT NULL,
                            created_at TIMESTAMPTZ DEFAULT Current_timestamp,
                            expires_at TIMESTAMPTZ NOT NULL,
                            CONSTRAINT fk_refresh_tokens_users FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE );

CREATE TABLE otp_auth(id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      otp_code       VARCHAR(100) DEFAULT NULL,
                      attempts       INTEGER NOT NULL DEFAULT 4,
                      active         BOOLEAN NULL DEFAULT FALSE,
                      verified_token UUID DEFAULT NULL UNIQUE,
                      contact        VARCHAR(100) UNIQUE,
                      updated_at     TIMESTAMPTZ DEFAULT NULL,
                      expires_at     TIMESTAMPTZ DEFAULT NULL,
                      cooldown       TIMESTAMPTZ);

CREATE TABLE stores(store_id      UUID PRIMARY KEY,
                    user_id UUID NOT NULL UNIQUE REFERENCES users(user_id),
                    name    VARCHAR(255),
                    api_key VARCHAR(64) UNIQUE NOT NULL);

CREATE TABLE products(product_id             BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
                      store_id       UUID NOT NULL REFERENCES stores(store_id),
                      name           VARCHAR(255) NOT NULL,
                      description    TEXT,
                      price          NUMERIC(12, 2) NOT NULL,
                      stock_quantity INTEGER NOT NULL DEFAULT 0,
                      created_at     TIMESTAMPTZ NOT NULL DEFAULT Now());

CREATE TABLE orders(id          uuid PRIMARY KEY,
                    customer_id UUID NOT NULL REFERENCES users(user_id),
                    store_id       UUID NOT NULL REFERENCES stores(store_id),
                    status      VARCHAR(50) NOT NULL DEFAULT 'pending',
                    total       NUMERIC(12, 2) NOT NULL,
                    created_at  TIMESTAMPTZ NOT NULL DEFAULT Now());

CREATE TABLE order_items(id         BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
                         order_id   uuid NOT NULL REFERENCES orders(id),
                         product_id BIGINT NOT NULL REFERENCES products(product_id),
                         quantity   INTEGER NOT NULL,
                         price      NUMERIC(12, 2) NOT NULL);
